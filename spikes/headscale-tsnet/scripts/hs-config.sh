#!/usr/bin/env bash
# Writes headscale/config.yaml for one phase of the spike.
#   BASE_DOMAIN   MagicDNS base domain (default ts.hlspike.test)
#   SPLIT         "domain=ip[,ip]" for dns.nameservers.split (empty: none)
#   EXTRA_PATH    1 to set dns.extra_records_path (the file must exist before Headscale starts)
# Headscale reads this file only at start; restart it after changing it.
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
BASE_DOMAIN=${BASE_DOMAIN:-ts.hlspike.test}
SPLIT=${SPLIT:-}
EXTRA_PATH=${EXTRA_PATH:-0}

split_yaml="    split: {}"
if [ -n "$SPLIT" ]; then
  dom=${SPLIT%%=*}; ips=${SPLIT#*=}
  split_yaml="    split:
      $dom:"
  IFS=, read -ra arr <<<"$ips"
  for ip in "${arr[@]}"; do split_yaml+="
        - $ip"; done
fi
extra_yaml=""
[ "$EXTRA_PATH" = 1 ] && extra_yaml="  extra_records_path: /etc/headscale/extra/records.json"

cat > "$here/headscale/config.yaml" <<EOF
# Spike config for headscale v0.29.7 (generated by scripts/hs-config.sh).
server_url: https://headscale.hlspike.test:8443
listen_addr: 0.0.0.0:8443
metrics_listen_addr: 0.0.0.0:9090
grpc_listen_addr: 127.0.0.1:50443
grpc_allow_insecure: false
trusted_proxies: []
noise:
  private_key_path: /var/lib/headscale/noise_private.key
prefixes:
  v4: 100.64.0.0/10
  v6: fd7a:115c:a1e0::/48
  allocation: sequential
derp:
  server:
    enabled: true
    region_id: 999
    region_code: "hlspike"
    region_name: "Spike embedded DERP"
    verify_clients: true
    stun_listen_addr: "0.0.0.0:3478"
    private_key_path: /var/lib/headscale/derp_server_private.key
    automatically_add_embedded_derp_region: true
    ipv4: 10.77.29.10
  urls: []
  paths: []
  auto_update_enabled: false
  update_frequency: 3h
disable_check_updates: true
node:
  expiry: 0
  ephemeral:
    inactivity_timeout: 30m
database:
  type: sqlite
  sqlite:
    path: /var/lib/headscale/db.sqlite
    write_ahead_log: true
tls_cert_path: /etc/headscale/tls/server.crt
tls_key_path: /etc/headscale/tls/server.key
log:
  level: info
  format: text
policy:
  mode: database
dns:
  magic_dns: true
  base_domain: $BASE_DOMAIN
  override_local_dns: false
  nameservers:
    global: []
$split_yaml
  search_domains: []
$extra_yaml
unix_socket: /var/run/headscale/headscale.sock
unix_socket_permission: "0770"
logtail:
  enabled: false
taildrop:
  enabled: false
auto_update:
  enabled: false
EOF
echo "wrote headscale/config.yaml (base_domain=$BASE_DOMAIN split='${SPLIT}' extra_records_path=$EXTRA_PATH)"
