//go:build ignore

// emoji_gen writes emoji_tables.go: the Emoji, Emoji_Presentation, Emoji_Modifier and Emoji_Modifier_Base properties
// from Unicode's emoji-data.txt, and the bases of the emoji variation sequences from emoji-variation-sequences.txt,
// for the Unicode version Go and golang.org/x/text use. And emoji_sequences_test.go: every recommended (RGI) emoji
// sequence, from emoji-sequences.txt and emoji-zwj-sequences.txt, which every name must be allowed to hold. It checks
// each file's SHA-256, so a regeneration reads what was reviewed.
//
//	go generate ./internal/manager/setup
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"slices"
	"strconv"
	"strings"
	"unicode"
)

const version = "17.0.0" // unicode.Version, and golang.org/x/text's tables17.0.0.go

var sources = map[string]string{ // file, under https://www.unicode.org/Public/<version>/: SHA-256
	"ucd/emoji/emoji-data.txt":                "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b",
	"ucd/emoji/emoji-variation-sequences.txt": "bb3d09ef03f206012c7532dd52dc0a21c9efddba0135ea4cf0d9201b8b9bba7e",
	"emoji/emoji-sequences.txt":               "12cc8267dc33cbd11ed32bcf6fc5dc2ad9c7a77bae1bdfba2f41b1b9b3ead8dd",
	"emoji/emoji-zwj-sequences.txt":           "5b25441daed2322b068c5e70cda522946a4f0274df864445a1965a92e5fc5cad",
}

func fetch(name string) []byte {
	url := "https://www.unicode.org/Public/" + version + "/" + name
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	b, err := io.ReadAll(resp.Body)
	if err != nil || resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %d %v", url, resp.StatusCode, err)
	}
	if sum := sha256.Sum256(b); hex.EncodeToString(sum[:]) != sources[name] {
		log.Fatalf("%s: SHA-256 %x, want %s", url, sum, sources[name])
	}
	return b
}

// lines yields each data line's fields, without comments.
func lines(b []byte, each func(fields []string)) {
	sc := bufio.NewScanner(bytes.NewReader(b))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		if strings.TrimSpace(line) == "" {
			continue
		}
		f := strings.Split(line, ";")
		for i := range f {
			f[i] = strings.TrimSpace(f[i])
		}
		each(f)
	}
}

func hexRune(s string) rune {
	n, err := strconv.ParseUint(s, 16, 32)
	if err != nil {
		log.Fatal(err)
	}
	return rune(n)
}

func main() {
	props := map[string][]rune{}
	lines(fetch("ucd/emoji/emoji-data.txt"), func(f []string) {
		lo, hi, ok := strings.Cut(f[0], "..")
		if !ok {
			hi = lo
		}
		for r := hexRune(lo); r <= hexRune(hi); r++ {
			props[f[1]] = append(props[f[1]], r)
		}
	})
	var bases []rune
	lines(fetch("ucd/emoji/emoji-variation-sequences.txt"), func(f []string) {
		seq := strings.Fields(f[0])
		if len(seq) == 2 && seq[1] == "FE0F" {
			bases = append(bases, hexRune(seq[0]))
		}
	})
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by emoji_gen.go from Unicode %s's emoji-data.txt and emoji-variation-sequences.txt. DO NOT EDIT.\n\npackage setup\n\nimport \"unicode\"\n\n", version)
	table(&out, "emojiProperty", "Unicode's Emoji property.", props["Emoji"])
	table(&out, "emojiPresentation", "Unicode's Emoji_Presentation property: emoji drawn as emoji without a VS16.", props["Emoji_Presentation"])
	table(&out, "emojiModifier", "Unicode's Emoji_Modifier property: the skin tones.", props["Emoji_Modifier"])
	table(&out, "emojiModifierBase", "Unicode's Emoji_Modifier_Base property: what a skin tone may follow.", props["Emoji_Modifier_Base"])
	table(&out, "variationBase", "The bases of the emoji variation sequences: what VS15 and VS16 may follow.", bases)
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("emoji_tables.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	sequences()
}

// sequences writes emoji_sequences_test.go: every RGI emoji sequence, each a code point range expanded.
func sequences() {
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by emoji_gen.go from Unicode %s's emoji-sequences.txt and emoji-zwj-sequences.txt. DO NOT EDIT.\n\npackage setup\n\n", version)
	fmt.Fprintln(&out, "// rgiSequences are Unicode's recommended (RGI) emoji sequences, with their type and name.")
	fmt.Fprintln(&out, "var rgiSequences = []struct{ kind, name, seq string }{")
	for _, file := range []string{"emoji/emoji-sequences.txt", "emoji/emoji-zwj-sequences.txt"} {
		lines(fetch(file), func(f []string) {
			var seqs []string
			if lo, hi, ok := strings.Cut(f[0], ".."); ok {
				for r := hexRune(lo); r <= hexRune(hi); r++ {
					seqs = append(seqs, string(r))
				}
			} else {
				var b strings.Builder
				for _, cp := range strings.Fields(f[0]) {
					b.WriteRune(hexRune(cp))
				}
				seqs = append(seqs, b.String())
			}
			for _, seq := range seqs {
				fmt.Fprintf(&out, "{%q, %q, %+q},\n", f[1], f[2], seq)
			}
		})
	}
	fmt.Fprintln(&out, "}")
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("emoji_sequences_test.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func table(w io.Writer, name, doc string, rs []rune) {
	slices.Sort(rs)
	rs = slices.Compact(rs)
	type rng struct{ lo, hi rune }
	var rr []rng
	for _, r := range rs {
		if n := len(rr); n > 0 && rr[n-1].hi+1 == r {
			rr[n-1].hi = r
		} else {
			rr = append(rr, rng{r, r})
		}
	}
	fmt.Fprintf(w, "// %s is %s\nvar %s = &unicode.RangeTable{\n", name, doc, name)
	var r16, r32 []rng
	for _, r := range rr {
		if r.hi <= 0xffff {
			r16 = append(r16, r)
		} else if r.lo > 0xffff {
			r32 = append(r32, r)
		} else {
			r16, r32 = append(r16, rng{r.lo, 0xffff}), append(r32, rng{0x10000, r.hi})
		}
	}
	latin := 0
	for _, r := range r16 {
		if r.hi <= unicode.MaxLatin1 {
			latin++
		}
	}
	fmt.Fprintln(w, "R16: []unicode.Range16{")
	for _, r := range r16 {
		fmt.Fprintf(w, "{0x%04x, 0x%04x, 1},\n", r.lo, r.hi)
	}
	fmt.Fprintln(w, "},\nR32: []unicode.Range32{")
	for _, r := range r32 {
		fmt.Fprintf(w, "{0x%x, 0x%x, 1},\n", r.lo, r.hi)
	}
	fmt.Fprintf(w, "},\nLatinOffset: %d,\n}\n\n", latin)
}
